// dsh-mind 激素版欲望引擎测试：方向 / 极值 / 兼容
// 用法：node tests/desire.mjs
import { 算欲望, 心情从激素 } from '../lib/host.js'

let 失败 = 0
const 断言 = (名, 条件, 详情 = '') => {
  if (条件) console.log('✓', 名, 详情)
  else {
    console.log('✗', 名, 详情)
    失败 += 1
  }
}
const f = (n) => Number(n).toFixed(3)
const 默认激素 = { 多巴胺: 50, 血清素: 190, 催产素: 5, 皮质醇: 350, 肾上腺素: 30 }
const 算 = (激素, 其他 = {}) =>
  算欲望({ hormones: 激素, 好感: 0.5, 精力: 0.8, 距上次聊天分钟: 120, 距上次刷站分钟: 300, 小时: 14, ...其他 })

console.log('\n=== 一、激素方向 ===')
const 高多巴胺 = 算({ ...默认激素, 多巴胺: 90 })
const 低多巴胺 = 算({ ...默认激素, 多巴胺: 10 })
断言('多巴胺越高越想刷视频', 高多巴胺.bili > 低多巴胺.bili, `${f(低多巴胺.bili)} → ${f(高多巴胺.bili)}`)
断言('多巴胺越低越想发呆', 低多巴胺.idle > 高多巴胺.idle, `${f(低多巴胺.idle)} > ${f(高多巴胺.idle)}`)

const 高催产素 = 算({ ...默认激素, 催产素: 10 })
const 低催产素 = 算({ ...默认激素, 催产素: 1 })
断言('催产素越高越想想聊天', 高催产素.chat > 低催产素.chat, `${f(低催产素.chat)} → ${f(高催产素.chat)}`)

const 高皮质醇 = 算({ ...默认激素, 皮质醇: 690 })
const 低皮质醇 = 算({ ...默认激素, 皮质醇: 138 })
断言('皮质醇高时更累（想睡觉更高）', 高皮质醇.sleep > 低皮质醇.sleep, `${f(低皮质醇.sleep)} → ${f(高皮质醇.sleep)}`)
断言('皮质醇高也会想找人倾诉', 高皮质醇.chat >= 低皮质醇.chat, `${f(低皮质醇.chat)} → ${f(高皮质醇.chat)}`)

const 高肾 = 算({ ...默认激素, 肾上腺素: 50 })
const 低肾 = 算({ ...默认激素, 肾上腺素: 10 })
断言('肾上腺素高时抗困（想睡觉更低）', 高肾.sleep < 低肾.sleep, `${f(低肾.sleep)} → ${f(高肾.sleep)}`)

console.log('\n=== 二、心情从激素 ===')
const 开心 = 心情从激素({ 多巴胺: 90, 血清素: 283, 催产素: 10, 皮质醇: 138, 肾上腺素: 50 })
const 难过 = 心情从激素({ 多巴胺: 10, 血清素: 101, 催产素: 1, 皮质醇: 690, 肾上腺素: 10 })
断言('多巴胺/血清素高、皮质醇低 → 心情高', 开心 > 0.8, f(开心))
断言('皮质醇拉满 → 心情低', 难过 < 0.2, f(难过))
断言('心情夹在 0~1', 开心 <= 1 && 难过 >= 0)

console.log('\n=== 三、极值 ===')
const 全低 = 算({ 多巴胺: 10, 血清素: 101, 催产素: 1, 皮质醇: 690, 肾上腺素: 10 })
const 全高 = 算({ 多巴胺: 90, 血清素: 283, 催产素: 10, 皮质醇: 138, 肾上腺素: 50 })
断言('全低：想刷/想聊都压得住（不爆表）', 全低.bili < 0.4 && 全低.chat < 0.5, `bili=${f(全低.bili)} chat=${f(全低.chat)}`)
断言('全高：想刷高', 全高.bili > 0.7, `bili=${f(全高.bili)}`)
断言('所有欲望在 0~1', Object.values(全低).every((v) => v >= 0 && v <= 1) && Object.values(全高).every((v) => v >= 0 && v <= 1))

console.log('\n=== 四、兼容（没传激素时用心情兜底）===')
const 不传激素 = 算欲望({ mood: 0.7, 好感: 0.5, 精力: 0.6, 距上次聊天分钟: 120, 距上次刷站分钟: 300, 小时: 14 })
断言('不传激素也能算（不崩）', Number.isFinite(不传激素.chat) && Number.isFinite(不传激素.bili), JSON.stringify(不传激素))

console.log('')
if (失败 > 0) {
  console.log(`FAIL：${失败} 项不通过`)
  process.exit(1)
}
console.log('DESIRE OK：激素方向 / 心情派生 / 极值 / 兼容 全部通过')
