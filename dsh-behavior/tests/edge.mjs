// dsh-behavior 极值校验：不校数值，只校逻辑（边界 / 单调性 / 阈值方向 / 夹紧）
// 用法：node tests/edge.mjs
import { 算冲动值 } from '../lib/host.js'

const 阈值 = 0.55
let 失败 = 0
const 断言 = (名, 条件, 详情 = '') => {
  if (条件) console.log('✓', 名, 详情)
  else {
    console.log('✗', 名, 详情)
    失败 += 1
  }
}
const 会开口 = (冲动) => 冲动 >= 阈值
const f = (n) => Number(n).toFixed(3)

console.log('\n=== 一、极值（0 / 1 边界）===')
const 全0 = 算冲动值(0, 0, 0, 1.4, 1)
断言('全 0 → 冲动 0，不开口', 全0.冲动 === 0 && !会开口(全0.冲动), `冲动=${f(全0.冲动)}`)

const 全1 = 算冲动值(1, 1, 1, 1.4, 1)
断言('全 1 + 冷太久 → 一定开口', 会开口(全1.冲动), `冲动=${f(全1.冲动)}`)

const 全1刚聊 = 算冲动值(1, 1, 1, 0.2, 1)
断言('全 1 但刚聊过 → 不开口', !会开口(全1刚聊.冲动), `冲动=${f(全1刚聊.冲动)}`)

const 全1没回3 = 算冲动值(1, 1, 1, 1.4, 0.2)
断言('全 1 但未回音阶段 3 → 收手不开口', !会开口(全1没回3.冲动), `冲动=${f(全1没回3.冲动)}`)

console.log('\n=== 二、单维拉满（看权重边界）===')
const 只有心情 = 算冲动值(1, 0, 0, 1.4, 1)
const 只有好感 = 算冲动值(0, 1, 0, 1.4, 1)
const 只有精力 = 算冲动值(0, 0, 1, 1.4, 1)
console.log(`  只有心情拉满: 基础 ${f(只有心情.基础)} → 冷太久冲动 ${f(只有心情.冲动)}`)
console.log(`  只有好感拉满: 基础 ${f(只有好感.基础)} → 冷太久冲动 ${f(只有好感.冲动)}`)
console.log(`  只有精力拉满: 基础 ${f(只有精力.基础)} → 冷太久冲动 ${f(只有精力.冲动)}`)
断言('心情拉满单独就够开口（权重最大）', 会开口(只有心情.冲动), f(只有心情.冲动))
断言(
  '好感 / 精力单独拉满都不够（不喧宾夺主）',
  !会开口(只有好感.冲动) && !会开口(只有精力.冲动),
)

console.log('\n=== 三、单调性（任一维升高，冲动不降）===')
for (const 维 of ['心情', '好感', '精力']) {
  let 上次 = -1
  let 单调 = true
  const 读数 = []
  for (let i = 0; i <= 10; i++) {
    const v = i / 10
    const 参 = { 心情: 0, 好感: 0, 精力: 0 }
    参[维] = v
    const r = 算冲动值(参.心情, 参.好感, 参.精力, 1.4, 1)
    读数.push(r.冲动)
    if (r.冲动 < 上次 - 1e-9) 单调 = false
    上次 = r.冲动
  }
  断言(`${维} 0→1 单调不减`, 单调, `0=${f(读数[0])} … 1=${f(读数[10])}`)
}

console.log('\n=== 四、时间因子单调（刚聊 < 中间 < 冷太久）===')
const 刚 = 算冲动值(0.7, 0.3, 0.6, 0.2, 1).冲动
const 中 = 算冲动值(0.7, 0.3, 0.6, 1.0, 1).冲动
const 冷 = 算冲动值(0.7, 0.3, 0.6, 1.4, 1).冲动
断言('刚聊过 < 中间 < 冷太久', 刚 < 中 && 中 < 冷, `${f(刚)} < ${f(中)} < ${f(冷)}`)

console.log('\n=== 五、未回音惩罚单调（阶段越高越不想开口）===')
const 阶段 = [1, 0.7, 0.4, 0.2].map((r) => 算冲动值(0.8, 0.4, 0.7, 1.4, r).冲动)
断言(
  '阶段 0 > 1 > 2 > 3',
  阶段[0] > 阶段[1] && 阶段[1] > 阶段[2] && 阶段[2] > 阶段[3],
  阶段.map(f).join(' > '),
)

console.log('\n=== 六、阈值边界（≥ 开口，< 不开口）===')
// 反推：让「只有心情 + 冷太久」的冲动恰好等于阈值
const 心情恰好 = 阈值 / 1.4 / 0.45
const r恰好 = 算冲动值(心情恰好, 0, 0, 1.4, 1)
断言(
  '冲动恰好 = 阈值 → 开口（≥ 的方向对）',
  Math.abs(r恰好.冲动 - 阈值) < 1e-9 && 会开口(r恰好.冲动),
  `冲动=${f(r恰好.冲动)}`,
)
const r略小 = 算冲动值(心情恰好 - 1e-6, 0, 0, 1.4, 1)
断言('冲动略小于阈值 → 不开口', !会开口(r略小.冲动), `冲动=${f(r略小.冲动)}`)

console.log('\n=== 七、输入越界夹紧（不许把怪值带进判断）===')
const 越界 = 算冲动值(5, -3, 'x', 1.4, 1)
断言(
  '心情 5 夹成 1、好感 -3 夹成 0、精力非法夹成 0',
  Math.abs(越界.基础 - 0.45) < 1e-9,
  `基础=${f(越界.基础)}`,
)
const 负因子 = 算冲动值(1, 1, 1, -2, 1)
断言('负的时间因子被夹回 0（不会变成负冲动）', 负因子.冲动 === 0, `冲动=${f(负因子.冲动)}`)

console.log('')
if (失败 > 0) {
  console.log(`FAIL：${失败} 项不通过`)
  process.exit(1)
}
console.log('EDGE OK：极值 / 单调 / 阈值方向 全部通过')
